#!/usr/bin/env python3
"""Build browser display data from an external experiment summary.

Only the figures used by the paper page are embedded. Full model outputs and
complete evaluation reports are never copied into the website.
"""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tagbench.paper import AUTHORS, MODELS, PAPER_TITLE, PAPER_URL, SUBSETS


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--summary", type=Path, required=True, help="External summary_metrics.json, or verified paper_results.json")
    ap.add_argument("--demo-data", type=Path, default=ROOT / "docs/assets/demos.json")
    ap.add_argument("--repository-url", default=None, help="Actual public GitHub URL, once created")
    args = ap.parse_args()
    if args.repository_url and not args.repository_url.startswith("https://github.com/"):
        ap.error("--repository-url must be a public https://github.com/ URL")
    summary = json.loads(args.summary.read_text(encoding="utf-8"))
    summary = summary.get("models", summary)
    models = []
    for identity, (name, group) in MODELS.items():
        source = summary[identity]
        overall = source["overall"]
        multi = source["by_multi_target"]["multi"]
        models.append({
            "id": identity, "name": name, "group": group,
            "overall": {
                "n": overall["n"], "miou": overall["mIoU"],
                "r03": overall["Recall@0.3"], "r05": overall["Recall@0.5"], "r07": overall["Recall@0.7"],
                "single": source["by_multi_target"]["single"]["mIoU"], "multi": multi["mIoU"],
                "fail": 1 - overall["MAE_Cvg"], "giou": overall["mgIoU"],
                "mae": overall["MAE_mid"], "cvg": overall["MAE_Cvg"],
            },
            "subsets": {tag: source["by_task_tag"][tag]["mIoU"] for tag, *_ in SUBSETS},
            "count": {
                "n": multi["n"], "accuracy": multi["count_acc"], "under": multi["count_under"],
                "over": multi["count_over"], "predictions": multi["avg_hyp_count"], "targets": multi["avg_gt_count"],
                "miou": multi["mIoU"],
            },
        })
    value = {
        "paper": {"title": PAPER_TITLE, "url": PAPER_URL, "authors": AUTHORS, "version": "v2", "repository_url": args.repository_url},
        "subsets": [{"tag": tag, "name": name, "n": n, "description": description} for tag, name, n, description, _ in SUBSETS],
        "models": models, "demos": json.loads(args.demo_data.read_text(encoding="utf-8")),
    }
    destination = ROOT / "docs/assets/data.js"
    encoded = json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False).replace("<", "\\u003c")
    destination.write_text("// Generated by scripts/build_site.py. Paper display values and three demo excerpts only.\nwindow.TAGBENCH_DATA = " + encoded + ";\n", encoding="utf-8")
    print(f"Built {destination.relative_to(ROOT)}: {len(models)} paper rows, {len(value['demos'])} audio examples")


if __name__ == "__main__":
    main()

